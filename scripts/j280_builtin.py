"""Built-in standalone frames of the v6 firmware (rtl/j280_swing/j280_builtin.v).

The built-in CONFIG + SWING are the board-validated 605 swing-up profile (design
D, 40%, comp 7% / 2.48%) with config_id 6001, no time limit, keepalive 20 ms
(bypassed in standalone) and the v6
trajectory defaults. `--write` regenerates the Verilog constants; `--check`
(and tests/test_j280_builtin.py) verifies the committed file matches.
"""
import argparse
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
import j280_traj as traj_math  # noqa: E402
import j280_v6_protocol as wire  # noqa: E402

SOURCE = ROOT / 'docs/data/swing-board-2026-10-18/swing-605-config.json'
VERILOG = ROOT / 'rtl/j280_swing/j280_builtin.v'
CONFIG_ID = 6001
# keepalive_ms is bypassed in standalone; 20 ms lets the bench prove the bypass quickly.
OVERRIDES = dict(config_id=CONFIG_ID, run_ms=0, keepalive_ms=20)
TRAJ = dict(move_dps=45, rotate_dps=60, accel_dps2=150, ki=0, i_window=80)


def profile():
    src = json.loads(SOURCE.read_text(encoding='utf-8'))
    values = dict(src['values'], **OVERRIDES)
    swing = dict(src['swing'], config_id=CONFIG_ID)
    traj = traj_math.default_params(**TRAJ)
    return dict(values=values, swing=swing, traj=traj)


def command_frames():
    """The two complete 192-byte command frames (sync, payload, CRC)."""
    p = profile()
    return (wire.build_command('config', p['values'], traj=p['traj']),
            wire.build_command('swing', p['swing']))


def frames():
    """(CONFIG payload, SWING payload, CONFIG CRC) as the guard sees them."""
    config, swing = command_frames()
    return config[2:190], swing[2:190], struct.unpack_from('<H', config, 190)[0]


def verilog():
    """Registered byte ROM: CONFIG frame at 0..191, SWING frame at 256..447."""
    config, swing = command_frames()
    lines = [
        '`timescale 1ns/1ps\n',
        '// Generated by scripts/j280_builtin.py from docs/data/swing-board-2026-10-18/swing-605-config.json\n',
        f'// (config_id {CONFIG_ID}, run_ms 0, trajectory {TRAJ}). Do not edit by hand.\n',
        '// Byte ROM of the two built-in command frames, injected into the command\n',
        '// parser for standalone runs: CONFIG at 0..191, SWING at 256..447.\n',
        'module j280_builtin (\n',
        '    input wire clk,\n',
        '    input wire [8:0] addr,\n',
        '    output reg [7:0] data\n',
        ');\n',
        '    always @(posedge clk)\n',
        '        case(addr)\n',
    ]
    for base, frame in ((0, config), (256, swing)):
        for i, byte in enumerate(frame):
            lines.append(f"            9'd{base + i}: data <= 8'h{byte:02x};\n")
    lines += ["            default: data <= 8'h00;\n", '        endcase\n', 'endmodule\n']
    return ''.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    text = verilog()
    if args.write:
        VERILOG.write_text(text, encoding='ascii', newline='\n')
        print(f'wrote {VERILOG}')
    if args.check:
        ok = VERILOG.is_file() and VERILOG.read_text(encoding='ascii') == text
        print('builtin up to date' if ok else 'builtin differs from generator')
        return 0 if ok else 1
    if not (args.write or args.check):
        print(json.dumps(profile(), indent=1))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
