`timescale 1ns/1ps
// 3PA1030 raw bus capture. No angle conversion or averaging is performed.
// Datasheet BA20241214A1: four-cycle pipeline, tOD=25 ns TYPICAL (no max).
// 5 MHz ADC clock; falling-edge capture leaves nominal 100 ns after rising.
module j280_adc_capture (
    input wire clk,
    input wire rst_n,
    input wire [9:0] adc_data,
    input wire adc_otr,
    output reg adc_clk,
    output wire adc_oe_n,
    output reg [9:0] raw,
    output reg valid,
    output reg sample_strobe,
    output wire [15:0] age_us
);
    reg [3:0] divider;
    assign adc_oe_n = 1'b0;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin divider <= 0; adc_clk <= 0; end
        else begin
            if (divider == 9) divider <= 0;
            else divider <= divider + 1'b1;
            if (divider == 4) adc_clk <= 1;
            if (divider == 9) adc_clk <= 0;
        end
    end

    reg [9:0] held_data;
    reg held_valid;
    reg [3:0] warmup;
    reg sample_toggle;
    // One intentional related-clock domain. Capture all parallel bits together.
    always @(negedge adc_clk or negedge rst_n) begin
        if (!rst_n) begin
            held_data <= 0;
            held_valid <= 0;
            warmup <= 0;
            sample_toggle <= 0;
        end else begin
            held_data <= adc_data;
            if (warmup < 8) warmup <= warmup + 1'b1;
            held_valid <= (warmup >= 7) && !adc_otr;
            sample_toggle <= ~sample_toggle;
        end
    end

    reg [9:0] bridge_data;
    reg bridge_valid, bridge_toggle;
    // ADC falling edge is generated by a master rising edge. Bridge on the
    // master FALLING edge, avoiding a coincident-edge interclock hold path.
    // These are related clocks; STA must check both half-cycle transfers.
    always @(negedge clk or negedge rst_n) begin
        if (!rst_n) begin
            bridge_data <= 0; bridge_valid <= 0; bridge_toggle <= 0;
        end else begin
            bridge_data <= held_data;
            bridge_valid <= held_valid;
            bridge_toggle <= sample_toggle;
        end
    end
    reg toggle_meta, toggle_sync;
    reg toggle_seen;
    reg [15:0] age_whole_us;
    reg [5:0] age_remainder;
    wire round_age = (age_remainder != 0) && (age_whole_us != 16'hffff);
    assign age_us = age_whole_us + (round_age ? 16'd1 : 16'd0);
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            toggle_meta <= 0; toggle_sync <= 0; toggle_seen <= 0;
            raw <= 0; valid <= 0; sample_strobe <= 0;
            age_whole_us <= 16'hffff; age_remainder <= 0;
        end else begin
            toggle_meta <= bridge_toggle;
            toggle_sync <= toggle_meta;
            toggle_seen <= toggle_sync;
            sample_strobe <= 0;
            if (toggle_sync != toggle_seen) begin
                // Held bus has been stable for three 50 MHz edges here.
                raw <= bridge_data;
                valid <= bridge_valid;
                sample_strobe <= 1;
                // 4*10 cycles ADC pipeline + 5 half-period + 3 handoff.
                // Nominal digital estimate, rounded up in microseconds.
                age_whole_us <= 0; age_remainder <= 6'd48;
            end else if (age_whole_us != 16'hffff) begin
                if (age_remainder == 49) begin
                    age_remainder <= 0;
                    age_whole_us <= age_whole_us + 1'b1;
                end else age_remainder <= age_remainder + 1'b1;
            end
        end
    end
endmodule
